inline bool ValidName(const std::string& name) {
    if(name.empty() || name.size()>48 || name.front()==' ' || name.back()==' ') return false;
    for(unsigned char c:name) if(!((c>='A'&&c<='Z')||(c>='a'&&c<='z')||(c>='0'&&c<='9')||c==' '||c=='_'||c=='-')) return false;
    return true;
}
